const available = Object.keys(SOURCES).filter((name) => existsSync(`src/${name}/main.ts`));

await mkdir("node_modules/.cache", { recursive: true });
const directory = await mkdtemp(resolve("node_modules/.cache/tascabile-runtime-"));
after(() => rm(directory, { recursive: true, force: true }));
// One Application for the module-level construction of every source; each test then
// installs a fresh runtime, as Paperback gives every extension its own.
globalThis.Application = ApplicationPolyfill();
await build({
  input: Object.fromEntries(available.map((name) => [name, `src/${name}/main.ts`])),
  external: ["@paperback/types", "@paperback/runtime-polyfills"],
  output: { dir: directory, format: "esm", entryFileNames: "[name].mjs" },
  logLevel: "silent",
});
const sources = Object.fromEntries(
  await Promise.all(
    available.map(async (name) => [
      name,
      (await import(pathToFileURL(`${directory}/${name}.mjs`).href))[name],
    ]),
  ),
);

/** Network stub: `handler(url, sentHeaders)` returns { status, body, headers?, url? }. */
let handler;
const fetched = [];
globalThis.fetch = async (input, init) => {
  // The polyfill always passes the URL as a string and headers as a plain object.
  const url = typeof input === "string" ? input : input instanceof URL ? input.href : input.url;
  // `Headers` lowercases names: "cookie", "user-agent".
  const sent = Object.fromEntries(new Headers(init?.headers));
  fetched.push({ url, headers: sent });
  const { status = 200, body = "", headers = {}, url: finalUrl } = await handler(url, sent);
  const response = new Response(body, { status, headers });
  Object.defineProperty(response, "url", { value: finalUrl ?? url });
  return response;
};

let sleeps;
async function install(source) {
  globalThis.Application = ApplicationPolyfill();
  sleeps = [];
  // The rate limiter pauses through Application.sleep: record the pause instead of waiting.
  Application.sleep = async (seconds) => {
    sleeps.push(seconds);
  };
  await source.initialise();
}

beforeEach(() => {
  fetched.length = 0;
  handler = () => ({ status: 200, body: "{}" });
});

const limiterOf = (source) =>
  source.mainRateLimiter ?? source.rateLimiter ?? source.globalRateLimiter;
const interceptorOf = (source) => source.mainInterceptor ?? source.requestManager;

for (const name of available) {
  await test(`${name}: limiter and main interceptor both see every request`, async () => {
    const source = sources[name];
    const spied = { limiter: limiterOf(source), interceptor: interceptorOf(source) };
    assert.ok(spied.limiter && spied.interceptor, "the source has both interceptors");
    assert.notEqual(spied.limiter.id, spied.interceptor.id);
    const calls = { limiter: 0, interceptor: 0 };
    for (const [role, target] of Object.entries(spied)) {
      const original = target.interceptRequest.bind(target);
      target.interceptRequest = async (request) => {
        calls[role]++;
        return original(request);
      };
    }
    try {
      await install(source);
      const requests = Array.from({ length: 8 }, (_, index) =>
        Application.scheduleRequest({ url: `${SOURCES[name]}?probe=${index}`, method: "GET" }),
      );
      await Promise.allSettled(requests);
      // Paperback keeps one interceptor per ID: MangaWorld and the six fansub readers
      // used to register both under one ID, so one of the two never ran.
      assert.deepEqual(calls, { limiter: 8, interceptor: 8 });
      assert.ok(sleeps.length > 0, "eight requests in a burst must schedule a pause");
    } finally {
      for (const target of Object.values(spied)) delete target.interceptRequest;
    }
  });
}

const CHALLENGE = {
  status: 403,
  headers: { "cf-mitigated": "challenge", "content-type": "text/html" },
  body: "<!DOCTYPE html><html><head><title>Just a moment...</title></head></html>",
};
const catalog = (...comics) => ({
  status: 200,
  headers: { "content-type": "application/json" },
  body: JSON.stringify({ comics }),
});
const COMIC = (title, slug = title.toLowerCase().replace(/\W+/gu, "-")) => ({
  title,
  slug,
  thumbnail: `https://example.test/${slug}.jpg`,
  adult: 0,
  author: "Autore",
  alt_titles: [],
  last_chapter: { url: `/read/${slug}/it/ch/1`, chapter: 1, published_on: "2026-10-01" },
});

const fansub = (name) => ({ skip: !sources[name] && `${name} missing` });

await test(
  "fansub: a Cloudflare challenge opens one banner, then the clearance is reused",
  fansub("HastaTeam"),
  async () => {
    const hasta = sources.HastaTeam;
    await install(hasta);
    const userAgent = await Application.getDefaultUserAgent();
    handler = (url, sent) =>
      /cf_clearance=ok/u.test(sent.cookie ?? "") ? catalog(COMIC("Gintama")) : CHALLENGE;

    const section = { id: "hasta_latest" };
    const first = await hasta.getDiscoverSectionItems(section, undefined).catch((error) => error);
    assert.equal(first.type, "cloudflareError");
    assert.equal(first.resolutionRequest.url, "https://reader.hastateam.com/");
    assert.equal(first.resolutionRequest.headers["User-Agent"], userAgent);

    // A second section loading at the same time must not open another banner.
    await assert.rejects(hasta.getDiscoverSectionItems(section, undefined), (error) => {
      assert.notEqual(error.type, "cloudflareError");
      assert.match(error.message, /già in corso/u);
      return true;
    });

    await hasta.cloudflareBypassCompleted(
      first.resolutionRequest,
      [{ name: "cf_clearance", value: "ok", domain: ".hastateam.com", path: "/" }],
      {},
    );
    const { items } = await hasta.getDiscoverSectionItems(section, undefined);
    assert.equal(items.length, 1);
    const last = fetched.at(-1);
    assert.match(last.headers.cookie, /cf_clearance=ok/u);
    // Same User-Agent as the check: Cloudflare ties the clearance to it.
    assert.equal(last.headers["user-agent"], userAgent);
  },
);

await test(
  "fansub: ordinary HTTP errors stay errors, never challenges or empty lists",
  fansub("LupiTeam"),
  async () => {
    const lupi = sources.LupiTeam;
    await install(lupi);
    for (const status of [403, 429, 500]) {
      handler = () => ({ status, body: "<html><title>Error</title></html>" });
      await assert.rejects(
        lupi.getDiscoverSectionItems({ id: "lupi_latest" }, undefined),
        (error) => {
          assert.notEqual(error.type, "cloudflareError");
          assert.match(error.message, new RegExp(`HTTP ${status}`, "u"));
          return true;
        },
      );
    }
    // A 200 HTML page instead of JSON is a readable error, not an empty catalogue.
    handler = () => ({ status: 200, body: "<!DOCTYPE html><p>Manutenzione</p>" });
    lupi.clearNetworkCache();
    await assert.rejects(lupi.getDiscoverSectionItems({ id: "lupi_latest" }, undefined), {
      name: "FansubResponseError",
      message: /pagina HTML/u,
    });
    // A challenged image does not open the banner (only API calls do).
    handler = () => CHALLENGE;
    const [response] = await Application.scheduleRequest({
      url: "https://lupiteam.net/storage/cover.jpg",
      method: "GET",
    });
    assert.equal(response.status, 403);
  },
);

await test(
  "fansub search: encoded segments, local search for slashes, no masked failures",
  fansub("TuttoAnimeManga"),
  async () => {
    const tam = sources.TuttoAnimeManga;
    await install(tam);
    const comics = [
      COMIC("1/2 Principe", "12_principe"),
      COMIC("100% Pascal-sensei"),
      COMIC("Bleach"),
    ];
    handler = (url) => (url.endsWith("/api/comics") ? catalog(...comics) : catalog(comics[1]));

    const prince = await tam.getSearchResults(
      { title: "1/2 Principe", metadata: {} },
      undefined,
      undefined,
    );
    assert.deepEqual(
      prince.items.map((item) => item.mangaId),
      ["12_principe"],
    );
    assert.ok(fetched.every((request) => !request.url.includes("/search/")));

    fetched.length = 0;
    const percent = await tam.getSearchResults(
      { title: "100%", metadata: {} },
      undefined,
      undefined,
    );
    assert.equal(fetched.at(-1).url, "https://tuttoanimemanga.net/api/search/100%25");
    assert.equal(percent.items.length, 1);

    // The local search still reports a failing catalogue instead of "no results".
    tam.clearNetworkCache();
    handler = () => ({ status: 500, body: "" });
    await assert.rejects(
      tam.getSearchResults({ title: "1/2", metadata: {} }, undefined, undefined),
      /HTTP 500/u,
    );
  },
);

await test(
  "fansub chapters keep the API order through sortingIndex; IDs stay the URLs",
  fansub("PhoenixScans"),
  async () => {
    const phoenix = sources.PhoenixScans;
    await install(phoenix);
    const chapter = (number, sub) => ({
      url: `/read/serie/it/ch/${number}${sub ? `/sub/${sub}` : ""}`,
      chapter: number,
      subchapter: sub,
      title: "",
      full_title: "",
      volume: null,
      language: "it",
      teams: [{ name: "Phoenix" }],
      published_on: "2026-10-01T00:00:00Z",
    });
    // Newest first, by chapter and part, as the live API lists them (8/2, 8/1, 8, 7…).
    const api = [
      chapter(24, 10),
      chapter(24, 2),
      chapter(24, 1),
      chapter(24, null),
      chapter(23, null),
    ];
    handler = () => ({
      status: 200,
      body: JSON.stringify({ comic: { title: "Serie", slug: "serie", chapters: api } }),
    });
    const chapters = await phoenix.getChapters({ mangaId: "serie", mangaInfo: {} });
    assert.deepEqual(
      chapters.map((item) => item.chapterId),
      api.map((item) => item.url),
    );
    assert.deepEqual(
      chapters.map((item) => item.sortingIndex),
      [5, 4, 3, 2, 1],
    );
    assert.deepEqual(
      chapters.map((item) => item.chapNum),
      [24, 24.2, 24.1, 24, 23],
    );
    assert.equal(chapters[0].title, "Parte 10");
    // Requests go straight to the canonical host, without the 301 from phoenixscans.com.
    assert.ok(fetched.every((request) => request.url.startsWith("https://www.phoenixscans.com/")));
  },
);

